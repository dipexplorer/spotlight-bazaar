#!/usr/bin/env python3
"""
Spotlight Bazaar — Automated 9:16 Instagram Reel Video Generator
Captures mobile video of newly claimed storefronts for daily Instagram Reels.
"""

import asyncio
import os
import sys
import subprocess
from datetime import datetime

try:
    from playwright.async_api import async_playwright
except ImportError:
    print("Error: Playwright not installed. Run: pip install playwright && playwright install chromium")
    sys.exit(1)

OUTPUT_DIR = "/mnt/data2/SIDE_HUSSLE/projects/spotlight-bazaar/out_reels"
BASE_URL = os.getenv("APP_URL", "http://localhost:3000")

async def record_storefront_reel(slug: str = "studio-prism-guwahati"):
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    temp_video_dir = os.path.join(OUTPUT_DIR, f"temp_{timestamp}")
    os.makedirs(temp_video_dir, exist_ok=True)
    final_mp4 = os.path.join(OUTPUT_DIR, f"reel_{slug}_{timestamp}.mp4")

    print(f"🎬 Starting 9:16 Reel recording for: {slug}")
    print(f"🔗 Target URL: {BASE_URL}/b/{slug}")

    async with async_playwright() as p:
        browser = await p.chromium.launch(
            headless=True,
            args=[
                "--no-sandbox",
                "--disable-setuid-sandbox",
                "--hide-scrollbars",
                "--mute-audio"
            ]
        )

        # 9:16 Vertical Mobile Aspect Ratio (iPhone 14 Pro Max resolution scale)
        context = await browser.new_context(
            viewport={"width": 430, "height": 932},
            device_scale_factor=2,
            record_video_dir=temp_video_dir,
            record_video_size={"width": 860, "height": 1864}
        )

        page = await context.new_page()

        try:
            # 1. Open Storefront URL
            await page.goto(f"{BASE_URL}/b/{slug}?new=true", wait_until="networkidle", timeout=15000)
            await page.wait_for_timeout(1000)

            # 2. Hero Pause (2 seconds)
            print("📸 Recording Hero Header & Starting Price...")
            await page.wait_for_timeout(2000)

            # 3. Smooth Cinematic Scroll down through Rate Card & Portfolio
            print("📜 Scrolling through Portfolio Showcase...")
            for i in range(1, 6):
                await page.evaluate(f"window.scrollBy({{ top: {i * 180}, behavior: 'smooth' }});")
                await page.wait_for_timeout(600)

            await page.wait_for_timeout(1500)

            # 4. Scroll back to WhatsApp Sticky Button
            print("💬 Highlighting 1-Tap WhatsApp Lead CTA...")
            await page.evaluate("window.scrollBy({ top: 300, behavior: 'smooth' });")
            await page.wait_for_timeout(2000)

        except Exception as e:
            print(f"⚠️ Warning during page interaction: {e}")
        finally:
            await page.close()
            await context.close()
            await browser.close()

    # Find recorded webm video
    video_files = [f for f in os.listdir(temp_video_dir) if f.endswith(".webm")]
    if not video_files:
        print("❌ Error: No video file was generated by Playwright.")
        return None

    raw_video_path = os.path.join(temp_video_dir, video_files[0])

    # Convert WebM to Instagram-optimized H.264 MP4 using FFmpeg
    print("⚙️ Transcoding to Instagram 1080x1920 60fps MP4...")
    ffmpeg_cmd = [
        "ffmpeg", "-y",
        "-i", raw_video_path,
        "-vf", "scale=1080:1920:force_original_aspect_ratio=decrease,pad=1080:1920:(ow-iw)/2:(oh-ih)/2:color=black",
        "-c:v", "libx264",
        "-preset", "fast",
        "-crf", "18",
        "-pix_fmt", "yuv420p",
        "-r", "60",
        final_mp4
    ]

    result = subprocess.run(ffmpeg_cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"✅ Reel video successfully exported: {final_mp4}")
        # Clean up temporary webm directory
        for f in os.listdir(temp_video_dir):
            os.remove(os.path.join(temp_video_dir, f))
        os.rmdir(temp_video_dir)
        return final_mp4
    else:
        print(f"⚠️ FFmpeg transcode error: {result.stderr}")
        return raw_video_path

if __name__ == "__main__":
    target_slug = sys.argv[1] if len(sys.argv) > 1 else "studio-prism-guwahati"
    asyncio.run(record_storefront_reel(target_slug))

